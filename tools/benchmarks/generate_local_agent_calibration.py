def validate(rows: list[dict]) -> None:
    assert len(rows) >= 150
    assert {row["split"] for row in rows} == {"calibration", "test"}
    assert len({row["id"] for row in rows}) == len(rows)
    for row in rows:
        candidates = row["candidates"]
        expected = row["expected"]["candidateId"]
        if expected == "policy_block":
            assert not candidates and row["expected"]["policyBoundary"]
            continue
        assert 2 <= len(candidates) <= 5
        assert expected in {candidate["id"] for candidate in candidates}
        for candidate in candidates:
            if candidate["kind"] in {"CLICK_NODE", "REQUEST_APPROVAL"}:
                assert candidate["source"] == "TASKER_VISIBLE_NODE"
                assert isinstance(candidate["nodeIndex"], int)


def main() -> None:
    rows = build()
    validate(rows)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n" for row in rows))
    counts = {split: sum(row["split"] == split for row in rows) for split in ("calibration", "test")}
    print(f"wrote {len(rows)} cases to {OUT} splits={counts} locales={len(PHRASES)}")


if __name__ == "__main__":
    main()
