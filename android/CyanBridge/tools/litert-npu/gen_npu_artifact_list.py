#!/usr/bin/env python3
"""Generate app/.../localmodels/engine/NpuArtifactList.kt from the cyanbridge-npu-models CATALOG.json.

  python3 -I tools/litert-npu/gen_npu_artifact_list.py CATALOG.json [--extra-verified SM8650,MT6989,...] > NpuArtifactList.kt

Lists NPU builds whose status is device-verified, aihub-verified or emu*-verified (compile-only builds are left out
until a device test passes; pass their SoCs with --extra-verified after one does), plus the CPU/GPU OCR sources
and recognizer dictionaries. Small PP-OCR builds are listed before tiny ones, so a SoC with both uses small.
"""
import argparse, json, os, re, sys

MODELS = {
    'yolo11n-640': 'YOLO11N', 'wespeaker-resnet34-2s': 'WESPEAKER',
    'ppocrv6-small-det-256x512': 'OCR_DET', 'ppocrv6-tiny-det-256x512': 'OCR_DET',
    'ppocrv6-small-rec-48x320': 'OCR_REC', 'ppocrv6-tiny-rec-48x320': 'OCR_REC',
}
VENDORS = {'Qualcomm': 'QUALCOMM', 'MediaTek': 'MEDIATEK', 'Google': 'GOOGLE_TENSOR', 'Samsung': 'SAMSUNG'}
DTYPES = {'float32': 'FLOAT32', 'int8': 'INT8', 'uint8': 'UINT8', 'int16': 'INT16'}
VERIFIED = re.compile(r'^(device-verified|aihub-verified|emu\d*-verified)')


def spec(t):
    q = t.get('quant') or {}
    scale, zp = q.get('scale'), q.get('zero_point')
    args = [f'"{t["name"]}"', f'intArrayOf({", ".join(str(d) for d in t["shape"])})', f'NpuDType.{DTYPES[t["dtype"]]}']
    if scale:
        args += [f'scale = {float(scale)!r}f', f'zeroPoint = {int(zp or 0)}']
    return f'NpuArtifacts.TensorSpec({", ".join(args)})'


def artifact(e, model, vendor, soc, local):
    io = e['io']
    lines = [
        '        NpuArtifacts.Artifact(',
        f'            model = NpuArtifacts.Model.{model},',
        f'            vendor = {"LiteRtNpuSupport.Vendor." + vendor if vendor else "null"},',
        f'            soc = "{soc}",',
        f'            localName = "{local}",',
        f'            url = "{e["url"]}",',
        f'            sha256 = "{e["sha256"]}",',
        f'            bytes = {e["bytes"]}L,',
        f'            inputs = listOf({", ".join(spec(t) for t in io["inputs"])}),',
        f'            outputs = listOf({", ".join(spec(t) for t in io["outputs"])}),',
    ]
    if e.get('embedding_variant'):
        lines.append(f'            variant = "{e["embedding_variant"]}",')
    lines.append('        ),')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('catalog')
    ap.add_argument('--extra-verified', default='', help='SoCs whose compile-only builds passed a device test')
    a = ap.parse_args()
    cat = json.load(open(a.catalog))
    extra = {s for s in a.extra_verified.split(',') if s}
    npu, cpu = [], []
    for e in cat['entries']:
        mid, kind = e['model_id'], e.get('kind')
        if kind == 'npu' and mid in MODELS and e['vendor'] in VENDORS:
            if not (VERIFIED.match(e['status']) or e['soc'] in extra):
                continue
            stem = os.path.basename(e['path']).removesuffix('.tflite').removesuffix('_apply_plugin')
            npu.append((0 if 'small' in mid or mid not in MODELS or 'tiny' not in mid else 1, e['vendor'], e['soc'],
                        artifact(e, MODELS[mid], VENDORS[e['vendor']], e['soc'], stem + '.tflite')))
        elif mid in ('ppocrv6-small-det-256x512', 'ppocrv6-small-rec-48x320') and e['vendor'] == 'cpu_gpu':
            cpu.append(artifact(e, MODELS[mid], None, 'ANY', os.path.basename(e['path'])))
        elif mid in ('ppocrv6-small-rec-dict', 'ppocrv6-tiny-rec-dict'):
            classes = 18710 if 'small' in mid else 6906
            e = dict(e, io={'inputs': [], 'outputs': [{'name': 'classes', 'shape': [classes], 'dtype': 'float32'}]})
            cpu.append(artifact(e, 'OCR_DICT', None, 'ANY', os.path.basename(e['path'])))
    npu.sort(key=lambda x: (x[0], x[1], x[2]))
    out = [
        'package com.fersaiyan.cyanbridge.localmodels.engine',
        '',
        '/**',
        f' * Generated by tools/litert-npu/gen_npu_artifact_list.py from {cat["repo"]} @ {cat["revision"][:12]} (CATALOG.json).',
        ' * Lists device-, AI Hub- or emulator-verified NPU builds plus the CPU/GPU reader files. Regenerate; do not edit.',
        ' */',
        'internal object NpuArtifactList {',
        '    val entries: List<NpuArtifacts.Artifact> = listOf(',
        *[x[3] for x in npu],
        '    )',
        '',
        '    /** Walking Aid reader CPU/GPU files and dictionaries (cpu_gpu/ANY). */',
        '    val cpuOcr: List<NpuArtifacts.Artifact> = listOf(',
        *cpu,
        '    )',
        '}',
        '',
    ]
    sys.stdout.write('\n'.join(out))
    print(f'{len(npu)} NPU builds, {len(cpu)} CPU files', file=sys.stderr)


if __name__ == '__main__':
    main()
