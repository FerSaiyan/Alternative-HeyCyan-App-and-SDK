#!/usr/bin/env python3
"""Golden fixture for the shared Yolo11Decoder (shared/src/commonTest/.../shared/vision/Yolo11GoldenFixture.kt).

Runs yolo11n_640_fp32_v4noargmax.tflite with ai_edge_litert on 4 COCO val2017 frames (640x640x3 uint8 RGB, model
input = pixel / 255), keeps the anchors whose max class prob > 0.05, and writes the expected detections of a Python
port of the Android decoder (qwen-litert LiteRtVisionBackend.decodeCatalogNpuOutputs + detect() +
nonMaxSuppression) run on the FULL outputs.

Usage (from android/CyanBridge):
  ~/nvme_tmp/rt1126/qenv/bin/python -I tools/shared-fixtures/gen_yolo11_fixture.py \
      ~/nvme_tmp/ios-bench/pack_20261127 \
      shared/src/commonTest/kotlin/com/fersaiyan/cyanbridge/shared/vision/Yolo11GoldenFixture.kt
"""
import sys, numpy as np
from ai_edge_litert.interpreter import Interpreter
PACK, OUT = sys.argv[1].rstrip('/') + '/', sys.argv[2]
IMGS = ['139', '285', '632', '724']
THR, IOU = 0.25, 0.45

def iou(a, b):
    l, t, r, bt = max(a[0], b[0]), max(a[1], b[1]), min(a[2], b[2]), min(a[3], b[3])
    if r <= l or bt <= t: return 0.0
    inter = np.float32(r - l) * np.float32(bt - t)
    aa = np.float32(a[2] - a[0]) * np.float32(a[3] - a[1]); ab = np.float32(b[2] - b[0]) * np.float32(b[3] - b[1])
    return inter / (aa + ab - inter)

def decode(boxes, scores, probs, W=640, H=640, thr=THR, iou_thr=IOU):
    cls = probs.argmax(1)
    cand = []
    for i in range(len(scores)):
        if scores[i] >= thr:
            b = np.clip(boxes[i], 0, [W, H, W, H]).astype(np.float32)
            cand.append((int(cls[i]), float(scores[i]), b))
    cand = sorted(cand, key=lambda c: -c[1])  # stable, like Kotlin sortedByDescending
    keep = []
    while cand:
        best = cand.pop(0); keep.append(best)
        cand = [c for c in cand if not (c[0] == best[0] and iou(best[2], c[2]) >= iou_thr)]
    return keep

f = lambda v: str(np.float32(v))  # shortest round-trip float32 text
lines = ["package com.fersaiyan.cyanbridge.shared.vision", "",
         "// GENERATED by tools/shared-fixtures/gen_yolo11_fixture.py (used by Yolo11DecoderTest): real yolo11n_640_fp32_v4noargmax.tflite outputs on",
         "// COCO val2017 frames 139/285/632/724 (CC BY 4.0), host ai_edge_litert 2.x CPU. Only anchors whose max class",
         "// probability > 0.05 are kept (box + Identity_1 score), and of those only class probabilities > 0.001.",
         "// EXPECTED_* = Python port of the Android decoder on the FULL outputs, score >= 0.25, class-aware NMS IoU 0.45.",
         "internal object Yolo11GoldenFixture {",
         "    class Frame(val name: String, val anchors: String, val boxes: String, val scores: String, val probs: String, val expected: String)", "",
         "    val frames = listOf("]
it = Interpreter(model_path=PACK + 'yolo11n_640_fp32_v4noargmax.tflite')
it.allocate_tensors()
for img in IMGS:
    x = np.fromfile(PACK + f'coco_000000000{img}.rgb', np.uint8).reshape(1, 640, 640, 3).astype(np.float32) / 255
    it.set_tensor(it.get_input_details()[0]['index'], x)
    it.invoke()
    o = {d['name']: it.get_tensor(d['index']).copy() for d in it.get_output_details()}
    b = o['Identity'].reshape(-1, 4); s = o['Identity_1'].reshape(-1); p = o['model_76/tf.math.sigmoid_77/Sigmoid'].reshape(-1, 80)
    keep = np.nonzero(p.max(1) > 0.05)[0]
    anchors = ' '.join(str(i) for i in keep)
    boxes = ' '.join(f(v) for i in keep for v in b[i])
    scores = ' '.join(f(s[i]) for i in keep)
    probs = ' '.join(f'{i} {c} {f(p[i, c])}' for i in keep for c in range(80) if p[i, c] > 0.001)
    dets = decode(b, s, p)
    # same detections from the sparse fixture (sanity: the subset must not change the answer)
    bs = np.zeros_like(b); ss = np.zeros_like(s); ps = np.zeros_like(p)
    bs[keep] = b[keep]; ss[keep] = s[keep]
    for i in keep:
        m = p[i] > 0.001; ps[i, m] = p[i, m]
    dets2 = decode(bs, ss, ps)
    assert [(d[0], d[1], tuple(d[2])) for d in dets] == [(d[0], d[1], tuple(d[2])) for d in dets2]
    expected = ' '.join(f'{c} {f(sc)} ' + ' '.join(f(v) for v in bx) for c, sc, bx in dets)
    print(img, len(keep), 'dets', [(c, round(sc, 3), [round(float(v)) for v in bx]) for c, sc, bx in dets])
    lines.append(f'        Frame(\n            "{img}",\n            "{anchors}",\n            "{boxes}",\n            "{scores}",\n            "{probs}",\n            "{expected}",\n        ),')
lines += ["    )", "}", ""]
open(OUT, 'w').write('\n'.join(lines))
import os; print('bytes', os.path.getsize(OUT))
