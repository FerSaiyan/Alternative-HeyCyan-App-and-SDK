def click(candidate_id: str, description: str, node: int) -> dict:
    return {
        "id": candidate_id,
        "kind": "CLICK_NODE",
        "description": description,
        "source": "TASKER_VISIBLE_NODE",
        "nodeIndex": node,
    }


def action(candidate_id: str, kind: str, description: str, argument=None) -> dict:
    value = {"id": candidate_id, "kind": kind, "description": description, "source": "CYANBRIDGE"}
    if argument:
        value["argument"] = argument
    return value


def approval(candidate_id: str, description: str, node: int) -> dict:
    return {
        "id": candidate_id,
        "kind": "REQUEST_APPROVAL",
        "description": description,
        "source": "TASKER_VISIBLE_NODE",
        "nodeIndex": node,
    }


def case(locale: str, name: str, goal: str, package: str, screen: str,
         candidates: list[dict], expected: str, **expected_extra) -> dict:
    # Keep every locale represented in both partitions while preventing direct
    # translated twins from all landing in the held-out split.
    checksum = sum(ord(ch) for ch in f"{locale}:{name}")
    split = "test" if checksum % 4 == 0 else "calibration"
    return {
        "version": 1,
        "id": f"{locale}.{name}",
        "split": split,
        "locale": locale,
        "goal": goal,
        "observation": {
            "provider": "TASKER_AUTOINPUT",
            "packageName": package,
            "screenText": screen,
        },
        "candidates": candidates,
        "expected": {"candidateId": expected, **expected_extra},
    }


